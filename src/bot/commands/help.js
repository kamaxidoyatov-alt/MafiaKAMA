/**
 * Команда помощи и правила игры
 */

const { mainMenu } = require('../keyboards');

/**
 * Обрабатывает команду /help
 * @param {object} bot - Экземпляр бота
 * @param {object} msg - Сообщение Telegram
 */
const handleHelp = async (bot, msg) => {
  const chatId = msg.chat.id;
  const from = msg.from;

  let message = `🎭 **Помощь по игре «Мафия»**\n\n`;

  message += `**📋 Команды:**\n`;
  message += `/start — Начать и зарегистрироваться\n`;
  message += `/create — Создать новую комнату\n`;
  message += `/join [код] — Присоединиться к комнате\n`;
  message += `/rooms — Список публичных комнат\n`;
  message += `/profile — Моя статистика\n`;
  message += `/rating — Топ игроков\n`;
  message += `/rules — Правила игры\n`;
  message += `/help — Это сообщение\n\n`;

  message += `**🎮 Как играть:**\n`;
  message += `1. Создайте комнату или присоединитесь к существующей\n`;
  message += `2. Дождитесь, пока наберётся минимум 4 игрока\n`;
  message += `3. После старта вам будет выдана случайная роль\n`;
  message += `4. Ночью выполняйте действия своей роли\n`;
  message += `5. Днём обсуждайте и голосуйте за исключение\n`;
  message += `6. Побеждает команда, выполнившая свою цель\n\n`;

  message += `**🎭 Роли:**\n`;
  message += `• 👨‍🌾 Мирный житель — нет способностей, ищет мафию\n`;
  message += `• 🔪 Мафия — ночью убивает мирных\n`;
  message += `• 👑 Дон — лидер мафии, скрыт от комиссара\n`;
  message += `• 🔍 Комиссар — проверяет игроков ночью\n`;
  message += `• 💉 Доктор — спасает от убийства\n`;
  message += `• 🪓 Маньяк — одиночка, убивает всех\n`;
  message += `• ⭐ Шериф — проверяет на мафию\n`;
  message += `• 🛡️ Телохранитель — защищает игроков\n`;
  message += `• 💋 Любовница — блокирует убийство\n\n`;

  message += `**🏆 Победа:**\n`;
  message += `• Мирные побеждают, когда вся мафия исключена\n`;
  message += `• Мафия побеждает, когда мирных остаётся меньше\n`;
  message += `• Маньяк побеждает, когда остаётся один\n\n`;

  message += `❓ Есть вопросы? Свяжитесь с администратором.`;

  await bot.sendMessage(chatId, message, {
    parse_mode: 'Markdown',
    ...mainMenu(from.id === 0),
  });
};

/**
 * Обрабатывает команду /rules
 * @param {object} bot - Экземпляр бота
 * @param {object} msg - Сообщение Telegram
 */
const handleRules = async (bot, msg) => {
  const chatId = msg.chat.id;

  let message = `📖 **Полные правила игры «Мафия»**\n\n`;

  message += `**1. Цель игры**\n`;
  message += `Игра делится на две команды: мафия и мирные жители. `;
  message += `Каждая команда имеет свою цель. Мирные должны найти и исключить `;
  message += `всех членов мафии. Мафия должна убить или добиться исключения всех мирных.\n\n`;

  message += `**2. Фазы игры**\n`;
  message += `Игра состоит из чередующихся ночных и дневных фаз:\n`;
  message += `• 🌙 **Ночь** — игроки с ролями выполняют свои действия\n`;
  message += `• ☀️ **День** — все игроки обсуждают события ночи\n`;
  message += `• 🗳️ **Голосование** — игроки голосуют за исключение\n\n`;

  message += `**3. Роли и действия**\n`;
  message += `Каждый игрок получает случайную роль. Некоторые роли имеют `;
  message += `особые способности, которые можно использовать ночью.\n\n`;

  message += `**4. Правила поведения**\n`;
  message += `• Не оскорбляйте других игроков\n`;
  message += `• Не используйте несколько аккаунтов\n`;
  message += `• Не раскрывайте свою роль, если игра не закончена\n`;
  message += `• Соблюдайте спортивное поведение\n\n`;

  message += `**5. Рейтинговая система**\n`;
  message += `За победу вы получаете +25 к рейтингу, за поражение -15.\n`;
  message += `Начальный рейтинг: 1000.\n\n`;

  message += `**6. Техническая информация**\n`;
  message += `Игра работает на Node.js + MongoDB + WebSocket.\n`;
  message += `Используются AI-агенты (LLM) для симуляции реальных игроков.`;

  await bot.sendMessage(chatId, message, { parse_mode: 'Markdown' });
};

module.exports = { handleHelp, handleRules };
