/**
 * Возвращает случайную личность
 * @returns {object} Личность
 */
const getRandomPersonality = () => {
  return personalities[Math.floor(Math.random() * personalities.length)];
};

/**
 * Возвращает личность по ID
 * @param {number} id - ID личности
 * @returns {object|null} Личность
 */
const getPersonalityById = (id) => {
  return personalities.find(p => p.id === id) || null;
};

/**
 * Возвращает всех личностей
 * @returns {Array} Массив личностей
 */
const getAllPersonalities = () => {
  return [...personalities];
};

